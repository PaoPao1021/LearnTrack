/* Isolated Web workflow; external AI responses are mocked, never billed. */
const { chromium } = require(process.env.LT_PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
(async () => {
 const browser = await chromium.launch({headless:true, ...(process.env.LT_BROWSER_PATH ? {executablePath:process.env.LT_BROWSER_PATH} : {})});
 try {
  const page = await browser.newPage({viewport:{width:1440,height:1000},locale:'zh-CN',timezoneId:'Asia/Shanghai'});
  const errors=[]; page.on('pageerror',e=>errors.push(e.message));
  const origin=process.env.LT_PREVIEW_ORIGIN || 'http://127.0.0.1:5183';
  fs.mkdirSync('output/playwright',{recursive:true});
  await page.goto(`${origin}/assistant`);
  await page.getByRole('heading',{name:'学习助手',exact:true}).waitFor();
  await page.waitForFunction(()=>document.querySelector('.brand-mark').dataset.motionPaused === 'false');
  assert.equal(await page.locator('.chrono-sweep').first().evaluate(e=>getComputedStyle(e).animationPlayState),'running');
  await page.getByRole('button',{name:'收起导航',exact:true}).click();
  assert.equal(await page.getByRole('button',{name:'展开导航',exact:true}).isVisible(),true);
  await page.getByRole('button',{name:'展开导航',exact:true}).click();
  await page.getByLabel('总结标题',{exact:true}).fill('积分复盘');
  await page.getByLabel('总结内容',{exact:true}).fill('换元积分时经常遗漏上下限，需要核对变量。');
  await page.getByRole('button',{name:'保存我的总结',exact:true}).click();
  await page.getByText('1 篇',{exact:true}).waitFor();
  await page.getByLabel('总结标题',{exact:true}).fill('未选择的私人总结');
  await page.getByLabel('总结内容',{exact:true}).fill('UNSELECTED_PRIVATE_NOTE');
  await page.getByRole('button',{name:'保存我的总结',exact:true}).click();
  await page.getByText('2 篇',{exact:true}).waitFor();
  await page.reload();
  await page.getByRole('checkbox',{name:'积分复盘',exact:true}).check();
  await page.getByRole('combobox',{name:'用途',exact:true}).selectOption('guide');
  await page.getByLabel('你的要求',{exact:true}).fill('结合总结，给出下次做题的检查步骤');
  const consent=page.getByRole('checkbox',{name:'同意将上述汇总、本次要求和已选总结发送到服务器配置的 AI 服务',exact:true});
  assert.equal(await page.getByRole('button',{name:'生成建议',exact:true}).isDisabled(),true);
  await consent.check();
  await page.getByRole('combobox',{name:'学习数据范围',exact:true}).selectOption('30');
  const expectedFrom = await page.evaluate(async()=>{ const {todayKey,shiftDateKey}=await import('/src/utils/index.ts'); return shiftDateKey(todayKey(),-29); });
  await page.waitForFunction(from=>document.querySelector('.agent-context')?.textContent.includes(from),expectedFrom);
  assert.equal(await consent.isChecked(),false,'changing context revokes previous send consent');
  await page.evaluate(async()=>{const {setSetting}=await import('/src/db/database.ts'); await setSetting('serverUrl','/');});
  let sent;
  await page.route('**/api/v1/agent/run',async route=>{
   sent=route.request().postDataJSON();
   await route.fulfill({json:{runId:'fe13215e-e945-4bfc-9cce-08d9ece62f41',task:'guide',model:'deepseek-flash',summary:'先标注新旧变量，再分别转换上下限，最后检查符号。',tasks:[]}});
  });
  await consent.check();
  await page.getByRole('button',{name:'生成建议',exact:true}).click();
  await page.getByText('先标注新旧变量，再分别转换上下限，最后检查符号。',{exact:true}).waitFor();
  assert.equal(sent.task,'guide'); assert.equal(sent.notes.length,1); assert.equal(sent.notes[0].title,'积分复盘');
  assert.equal(JSON.stringify(sent).includes('UNSELECTED_PRIVATE_NOTE'),false);
  await page.getByRole('button',{name:'保存到总结库',exact:true}).click();
  await page.getByText('3 篇',{exact:true}).waitFor();
  await page.reload();
  await page.getByRole('checkbox',{name:/学习指导/}).waitFor();
  await page.getByRole('checkbox',{name:/学习指导/}).check();
  await page.screenshot({path:'output/playwright/assistant-library-light.png',fullPage:true,animations:'disabled'});
  await page.getByRole('button',{name:'切换深色',exact:true}).click();
  await page.waitForFunction(()=>document.documentElement.classList.contains('dark'));
  await page.evaluate(()=>window.scrollTo(0,0));
  await page.screenshot({path:'output/playwright/assistant-dark.png',animations:'disabled'});
  await page.emulateMedia({reducedMotion:'reduce'});
  assert.equal(await page.locator('.chrono-sweep').first().evaluate(e=>getComputedStyle(e).animationName),'none');
  await page.emulateMedia({reducedMotion:'no-preference'});
  await page.route('**/api/v1/agent/capabilities',route=>route.fulfill({json:{version:2,configured:true,provider:'DeepSeek',model:'deepseek-flash',tasks:['review','plan','guide']}}));
  await page.getByRole('link',{name:'DeepSeek 接入设置',exact:true}).click();
  await page.getByRole('button',{name:'读取服务器 AI 配置',exact:true}).click();
  await page.getByText('DeepSeek 已配置 · deepseek-flash',{exact:true}).waitFor();
  await page.getByText('DeepSeek 接入步骤',{exact:true}).click();
  await page.locator('#agent-connection').screenshot({path:'output/playwright/assistant-connection.png',animations:'disabled'});
  await page.setViewportSize({width:680,height:820});
  await page.goto(`${origin}/assistant`);
  await page.getByRole('heading',{name:'学习助手',exact:true}).waitFor();
  await page.screenshot({path:'output/playwright/assistant-narrow.png',animations:'disabled'});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  assert.deepEqual(errors,[]);
  console.log('PASS: persistent summaries, selected-only context, consent reset, mocked guidance/archive/reuse, DeepSeek config status, navigation pill and continuous/reduced logo motion.');
 } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exit(1)});
