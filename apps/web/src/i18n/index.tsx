const dictionaries: Record<Lang, Record<MessageKey, string>> = { zh, en };

function initialLang(): Lang {
  try {
    const stored = localStorage.getItem(STORAGE_KEY);
    if (stored === 'zh' || stored === 'en') return stored;
  } catch { /* storage blocked */ }
  return typeof navigator !== 'undefined' && navigator.language?.toLowerCase().startsWith('zh') ? 'zh' : 'en';
}

interface I18nValue {
  lang: Lang;
  setLang: (lang: Lang) => void;
  /** Intl locale for dates/times */
  locale: string;
  t: (key: MessageKey, vars?: Vars) => string;
  /** duration formatter bound to the current language */
  fmtDuration: (seconds: number) => string;
}

const I18nContext = createContext<I18nValue | null>(null);

function interpolate(text: string, vars?: Vars): string {
  if (!vars) return text;
  let out = text;
  for (const [key, value] of Object.entries(vars)) out = out.replaceAll(`{${key}}`, String(value));
  return out;
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>(initialLang);

  useEffect(() => {
    document.documentElement.lang = lang === 'zh' ? 'zh-CN' : 'en';
    try { localStorage.setItem(STORAGE_KEY, lang); } catch { /* storage blocked */ }
  }, [lang]);

  const value = useMemo<I18nValue>(() => ({
    lang,
    setLang,
    locale: lang === 'zh' ? 'zh-CN' : 'en-US',
    t: (key, vars) => interpolate(dictionaries[lang][key] ?? zh[key] ?? key, vars),
    fmtDuration: (seconds) => formatDuration(seconds, lang),
  }), [lang]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useI18n must be used inside <I18nProvider>');
  return ctx;
}

/** Translate a data-layer error: AppError codes are looked up, raw strings pass through. */
export function translateError(error: unknown, t: (key: MessageKey, vars?: Vars) => string): string {
  const raw = error instanceof Error ? error.message : String(error);
  try {
    const parsed = JSON.parse(raw) as { code?: string; params?: Vars };
    if (parsed && typeof parsed.code === 'string' && parsed.code in zh) return t(parsed.code as MessageKey, parsed.params);
  } catch { /* plain string */ }
  if (raw in zh) return t(raw as MessageKey);
  return raw;
}
